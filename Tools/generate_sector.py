#!/usr/bin/env python3
"""One versioned sector catalog for browser and native simulation."""
import json
from pathlib import Path
import sys
root=Path(__file__).resolve().parents[1]
data=json.loads((root/'Shared/sector.json').read_text())
lines=['#pragma once','// Generated by Tools/generate_sector.py from Shared/sector.json.','#include <array>','namespace HelioExplore {','enum class Kind { Station, Field, Derelict, Signal, Planet, Moon, Ruin, Beacon };','struct Site { const char* id; const char* name; Kind kind; std::array<double,3> position; double radius; int reward; bool artifact; const char* lore; };',f'inline constexpr std::array<Site,{len(data["sites"])}> Sites{{{{']
for s in data['sites']:
    pos=','.join(str(v)+'.0' if isinstance(v,int) else str(v) for v in s['position'])
    lines.append('    {'+f'{json.dumps(s["id"])},{json.dumps(s["name"])},Kind::{s["kind"].title()},{{{{{pos}}}}},{s["radius"]},{s["reward"]},{str(s["artifact"]).lower()},{json.dumps(s["lore"])}'+'},')
lines+=['}};','}']
text='\n'.join(lines)+'\n';p=root/'Source/Heliopause/Public/SectorCatalog.h'
if '--check' in sys.argv:
    assert p.read_text()==text,'Native sector catalog differs from browser source'
    print('PASS: shared sector catalog is synchronized')
else:p.write_text(text)
